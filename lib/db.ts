import postgres from 'postgres';

const globalForDb = globalThis as unknown as { sql?: postgres.Sql };

// Keep `date` columns as 'YYYY-MM-DD' strings so IST dates never shift.
// prepare: false — Neon's pooler keeps server connections open across deploys, so a query prepared before a
// schema change (e.g. `select *` before a new column) keeps failing with "cached plan must not change result type".
// Unprepared queries are planned fresh each time, which is fine at this size.
export const sql =
  globalForDb.sql ??
  postgres(process.env.DATABASE_URL!, {
    max: 5,
    prepare: false,
    types: {
      date: { to: 1082, from: [1082], serialize: (x: string) => x, parse: (x: string) => x },
    },
  });

if (process.env.NODE_ENV !== 'production') globalForDb.sql = sql;

export type Tx = postgres.TransactionSql;

export type Role = 'player' | 'core' | 'admin';
export type Lang = 'en' | 'mr' | 'hi';

export const SKILL_LEVELS = ['basic', 'intermediate', 'advanced'] as const;
export type SkillLevel = (typeof SKILL_LEVELS)[number];
export const GENDERS = ['male', 'female', 'other'] as const;
export type Gender = (typeof GENDERS)[number];

export type Player = {
  id: number;
  first_name: string;
  last_name: string;
  /** Generated by Postgres from first + last name (read-only). */
  name: string;
  phone: string;
  role: Role;
  pin_hash: string | null;
  pin_reset_requested_at: Date | null;
  deactivated_at: Date | null;
  /** Soft-deleted by an admin: hidden from every list. Deleting also deactivates. */
  deleted_at: Date | null;
  deleted_by: number | null;
  /** Self sign-ups are null until core/admin approve them. */
  approved_at: Date | null;
  email: string | null;
  skill_level: SkillLevel | null;
  gender: Gender | null;
  created_at: Date;
  lang: Lang;
};

export type Batch = {
  id: string;
  label: string;
  start_time: string; // 'HH:MM:SS' IST
  duration_min: number;
  courts: number;
  court_numbers: number[];
  players_per_court: number;
  price_rupees: number;
};

export type Session = {
  id: number;
  batch_id: string;
  date: string;
  starts_at: Date;
  capacity: number;
  court_numbers: number[];
  locked: boolean;
  closed: boolean;
  cancelled: boolean;
};

export type PlanType = 'fixed' | 'wallet';

export type Membership = {
  id: number;
  player_id: number;
  kind: PlanType;
  batch_id: string | null; // null for wallet plans
  days: number[];
  sessions_total: number;
  sessions_used: number;
  starts_on: string;
  ends_on: string | null;
  note: string | null;
  amount_rupees: number | null;
  status: 'active' | 'ended';
};

/** What a player asks for. 'wallet' = top up a balance usable in any batch, any day. */
export type PlanKind = 'month' | 'weekdays' | 'weekends' | 'wallet';

export type BookingStatus = 'booked' | 'confirmed' | 'withdrawn' | 'present' | 'no_show';

export type Booking = {
  id: number;
  session_id: number;
  player_id: number;
  guests: number;
  status: BookingStatus;
  source: 'self' | 'auto';
  membership_id: number | null;
  charged: boolean;
  paid: boolean;
  /** The fee collected, fixed when staff marked it paid. */
  paid_rupees: number | null;
};
