const DICTS: Record<Lang, Dict> = { en, mr, hi };

export type T = (key: Key, vars?: Record<string, string | number>) => string;

export function translator(lang: Lang): T {
  const dict = DICTS[lang] ?? en;
  return (key, vars) => {
    let s = dict[key] ?? en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}

export const isKey = (k: string): k is Key => k in en;

export const langName = (lang: Lang) => DICTS[lang].langName;

/** Batch label in the viewer's language, falling back to the stored label. */
export const batchName = (t: T, batch: { id: string; label: string }) => {
  const k = `batch_${batch.id}`;
  return isKey(k) ? t(k) : batch.label;
};

/** 'Mon–Fri', 'All days', 'Weekends' or 'Mon, Wed, Fri'. */
export function daysLabel(t: T, days: number[]): string {
  const set = [...days].sort().join(',');
  if (set === '0,1,2,3,4,5,6') return t('days_all');
  if (set === '1,2,3,4,5') return t('days_weekdays');
  if (set === '0,6') return t('days_weekends');
  return [...days].sort((a, b) => ((a + 6) % 7) - ((b + 6) % 7)).map((d) => t(`d${d}` as Key)).join(', ');
}
